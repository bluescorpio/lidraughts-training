/**
 * Rebuild src/content/packData.js from src/content/materials.
 * Run: node scripts/build-content-pack.mjs
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const materials = join(root, 'src/content/materials');
const index = JSON.parse(readFileSync(join(materials, 'games-index.json'), 'utf8'));
const puzzles = JSON.parse(readFileSync(join(materials, 'kill-puzzles-final.json'), 'utf8'));
const overviewMd = readFileSync(join(materials, '00-复盘总览.md'), 'utf8');

const pdns = {};
for (const name of readdirSync(join(materials, 'pdns'))) {
  if (!name.endsWith('.pdn')) continue;
  const folder = name.replace(/\.pdn$/i, '');
  pdns[folder] = readFileSync(join(materials, 'pdns', name), 'utf8');
}

const overview = [];
for (const line of overviewMd.split(/\r?\n/)) {
  const match = line.match(/^\|\s*(\d{4}-\d{2}-\d{2})\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*([^|]+?)\s*\|\s*\[`([^`]+)`\]/);
  if (!match) continue;
  const folder = match[5].replace(/\/$/, '');
  const row = index.find((item) => item.folder === folder);
  overview.push({
    date: match[1],
    opponent: match[2],
    result: match[3],
    summary: match[4],
    folder,
    pdn: row?.pdn || null,
  });
}

const pack = {
  index,
  puzzles: puzzles.map((item) => {
    const next = { ...item };
    delete next.scan;
    return next;
  }),
  pdns,
  overview,
};

const out = `/* Generated by scripts/build-content-pack.mjs. Do not edit by hand. */\nexport const PACK = ${JSON.stringify(pack)};\n`;
writeFileSync(join(root, 'src/content/packData.js'), out);
console.log(`wrote packData.js games=${Object.keys(pdns).length} puzzles=${puzzles.length} overview=${overview.length}`);
